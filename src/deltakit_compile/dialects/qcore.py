# region Quantum effect traits


class QuantumEffectKind(IntEnum):
    """The kind of quantum side effects an operation can have."""

    RESET = 0
    """Resets one or more qubits."""
    STATE_CHANGE = 1
    """Changes the state of one or more qubits, i.e., a gate effect."""
    MEASURE = 2
    """Measures and destroys one or more qubits."""
    PATCH = 3
    """Operates on patches which can involve stabiliser measurements, ancilla measurements,
    state changes, and resetting"""
    DECODING = 4
    """Operations on quantum state that has the side effect of modifying the decoding problem that
    the QEC system manages, e.g. adding a detector has a side effect on calculating logical
    corrections."""


@dataclass(frozen=True)
class QuantumEffectInstance:
    """An instance of a quantum side effect."""

    kind: QuantumEffectKind
    """The kind of quantum effect."""
    value: SSAValue | None = field(default=None)
    """The SSAValue of the qubits affected, if known."""


class QuantumEffect(OpTrait, ABC):
    """A trait that enables operations to expose their side-effects or absence thereof."""

    @abstractmethod
    def get_effects(self, op: Operation) -> set[QuantumEffectInstance] | None:
        """Returns the concrete quantum side effects of the operation.
        Return None if it can't be figured out - interpreted as unknown effects.

        Args:
            op: The `Operation`, that has this trait, for which the `QuantumEffectInstance`s will
                refer to.

        Returns:
            The `set` of `QuantumEffectInstances` generated by this trait on the given `Operation`.
        """

    def has_effects(self, op: Operation) -> bool:
        """Returns True iff the operation has known concrete side effects generated by this trait.

        Args:
            op: The `Operation`, that has this trait, to check for quantum effects .

        Returns:
            True iff op has at least 1 well defined quantum effect generated by this trait.
        """
        effects = self.get_effects(op)
        return (effects is not None) and len(effects) > 0


def get_quantum_effects(op: Operation) -> set[QuantumEffectInstance] | None:
    """Gets the known quantum side effects of an operation, under-approximating for safety.
    `op` has no quantum effects if this method returns `set()`.

    Args:
        op: An `Operation` to check get the QuantumEffectInstances of.

    Returns:
        A `set` of all the `QuantumEffectInstance`s produced by the traits of `op`, or
        None if `op` has unknown effects.
    """

    effect_interfaces = op.get_traits_of_type(QuantumEffect)
    if not effect_interfaces:
        return None

    effects = set[QuantumEffectInstance]()
    for interface in effect_interfaces:
        interface_effects = interface.get_effects(op)
        if interface_effects is None:
            return None
        effects.update(interface_effects)

    return effects


def has_quantum_effect(op: Operation, effect: QuantumEffectKind) -> bool:
    """Returns True if the operation has the given side effect. Returning False may mean the
    operation has unknown quantum effects.

    Args:
        op: The `Operation` to test for quantum effects.
        effect: The kind of quantum effect to check for.

    Returns:
        True if `op` has the specified quantum effect. Returns false if `op` does not, or if
        the quantum effects of `op` are unknown.
    """
    effects = get_quantum_effects(op)
    return effects is not None and any(e.kind == effect for e in effects)


def is_quantum_effect_free(op: Operation) -> bool:
    """Checks if a generic operation is quantum side effect free for sure.

    Args:
        op: The `Operation` to check for quantum effects.

    Returns:
        True iff `op` definitely has no quantum side effects.
    """
    effects = get_quantum_effects(op)
    return effects is not None and len(effects) == 0


def is_quantum_state_effect_free(op: Operation) -> bool:
    """Checks if a generic operation is free of side effects that change the quantum state.

    The operation may have side effects that change the decoding problem.

    Args:
        op: The `Operation` to check for side effects that change the quantum state.

    Returns:
        True iff `op` definitely has no quantum side effects that change the quantum state.
    """
    quantum_state_effects = {
        QuantumEffectKind.RESET,
        QuantumEffectKind.STATE_CHANGE,
        QuantumEffectKind.MEASURE,
        QuantumEffectKind.PATCH,
    }
    effects = get_quantum_effects(op)
    return effects is not None and all(e.kind not in quantum_state_effects for e in effects)


class NoQuantumEffect(QuantumEffect):
    """A trait that signals that an operation never has quantum side effects."""

    @override
    def get_effects(self, op: Operation) -> set[QuantumEffectInstance]:
        return set()


@dataclass(frozen=True)
class QuantumOperandEffect(QuantumEffect):
    """A trait that signals that an operation is one that directly affects qubit state of an
    operand.

    Attributes:
        operand_name: The string name of the operand (including optional or variadic) that is
            affected by the `Operation` with this trait.

    Args:
        operand_name: The string name of an operand (including optional or variadic) defined for
            the `Operation` this trait applies to.
    """

    operand_name: str

    @override
    def verify(self, op: Operation) -> None:
        assert isinstance(op, IRDLOperation)
        op_def = op.get_irdl_definition()

        operand_names = [name for name, _ in op_def.operands]
        if self.operand_name not in operand_names:
            msg = f"{op.name} doesn't have operand '{self.operand_name}'"
            raise VerifyException(msg)

    @override
    def get_effects(self, op: Operation) -> set[QuantumEffectInstance]:
        value = cast(SSAValues | SSAValue | None, getattr(op, self.operand_name))
        # This getattr/cast is safe because verify() ensure the operand_name is a valid op operand
        if value is None:
            # The operand was optional and the Quantum effect is only on operands that exist.
            return set()
        if isinstance(value, SSAValues):
            return {QuantumEffectInstance(self.kind(), v) for v in value}
        return {QuantumEffectInstance(self.kind(), value)}

    @classmethod
    @abstractmethod
    def kind(cls) -> QuantumEffectKind:
        """Returns the QuantumEffectKind associated with this QuantumEffect."""


