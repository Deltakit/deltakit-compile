@irdl_op_definition
class AllocQubitOp(IRDLOperation):
    """Allocate qubits and/or registers of qubits. This can only be done in the global scope."""

    name = "qcore.alloc_qubit"

    _Q: ClassVar[IntConstraint] = IntVarConstraint("Qubit_Count", AnyInt())
    _QC: ClassVar[IntConstraint] = MessageIntConstraint(
        _Q, "Number of coordinates and allocated qubits do not match."
    )
    _QI: ClassVar[IntConstraint] = MessageIntConstraint(
        _Q, "Number of ids and allocated qubits do not match."
    )

    coords = opt_prop_def(
        ArrayOfConstraint(  # multiple coordinates are stored in a ArrayAttr
            SetOf(  # coordinates must be unique
                RangeOf(
                    QubitCoordinateAttr.constr(
                        MessageIntConstraint(
                            IntVarConstraint("Coordinate_Dimensions", AnyInt()),
                            f"All coordinates in a {name} must have the same number of dimensions.",
                        )
                    )
                ),
            ).of_length(_QC)
        )
    )

    ids = opt_prop_def(
        ArrayOfConstraint(  # multiple ids are stored in a ArrayAttr
            SetOf(  # ids must be unique
                RangeOf(IntAttr)
            ).of_length(_QI)
        )
    )

    result = var_result_def(SumOver(RangeOf(base(QubitType) | base(QubitRegType)), qubit_count, _Q))

    traits = traits_def(Pure(), NoQuantumEffect(), HasProgramParent())

    assembly_format = (
        f"(`<` {AllocQubitPropsDirective.use('$coords', '$ids')}^ `>`)?"
        " attr-dict `->` type($result)"
    )
    custom_directives = (AllocQubitPropsDirective,)

    def __init__(
        self,
        results: Sequence[QubitType | QubitRegType] | QubitType | QubitRegType,
        coordinates: Iterable[QubitCoordinateAttr | Iterable[FloatAttr[Float64Type] | float]]
        | None = None,
        ids: Iterable[IntAttr | int] | None = None,
    ):
        if isinstance(results, QubitType | QubitRegType):
            results = [results]
        super().__init__(
            result_types=(results,),
            properties={
                "coords": None
                if coordinates is None
                else ArrayAttr(
                    [QubitCoordinateAttr.coerce(coordinate) for coordinate in coordinates]
                ),
                "ids": None if ids is None else ArrayAttr([IntAttr.get(id_) for id_ in ids]),
            },
        )

    def qubit_count(self) -> int:
        """Returns the number of qubits allocated by this operation."""
        return sum(qubit_count(res.type) for res in self.results)

    def _get_qubit_pos(
        self, qubit: SSAValue[QubitType | QubitRegType], index: int | None = None
    ) -> int:
        """Get the position in the per-individual-qubit data arrays of a given qubit allocated by
        this operation.

        Args:
            qubit: The SSA value of the qubit or qubit register to get the attributes of.
            index: If the qubit is a register, the index of the desired qubit within the register.
                If `qubit` is of `QubitType` this must be `None` otherwise it must be between `0`
                and the size of the qubit register.

        Returns:
            The index into the per-individual-qubit data that refers to the specified qubit.
        """
        if index is not None and isinstance(qubit.type, QubitType):
            msg = "Index provided for a single qubit."
            raise TypeError(msg)
        if isinstance(qubit.type, QubitRegType):
            if index is None:
                msg = "Qubit register provided without an index."
                raise TypeError(msg)
            if index >= len(qubit.type):
                msg = f"Index {index} out of bounds for qubit register of size {len(qubit.type)}."
                raise IndexError(msg)

        try:
            qubit_idx = self.result.index(qubit)
        except ValueError:
            msg = "The given qubit is not allocated by this operation."
            raise ValueError(msg) from None

        qubit_pos = sum(qubit_count(res.type) for res in self.result[:qubit_idx])
        if index is not None:
            qubit_pos += index

        return qubit_pos

    @overload
    def get_qubit_coordinate(
        self, qubit: SSAValue[QubitType], index: None = None
    ) -> QubitCoordinateAttr | None: ...

    @overload
    def get_qubit_coordinate(
        self, qubit: SSAValue[QubitRegType], index: int
    ) -> QubitCoordinateAttr | None: ...

    def get_qubit_coordinate(
        self, qubit: SSAValue[QubitType | QubitRegType], index: int | None = None
    ) -> QubitCoordinateAttr | None:
        """Find the coordinate of a qubit allocated by this operation.

        Args:
            qubit: The SSA value of the qubit or qubit register to get the coordinate of.
            index: If the qubit is a register, the index of the desired qubit within the register.

        Returns:
            The coordinate attribute of the specified qubit, or None if this operation doesn't
            assign coordinates.

        Raises:
            TypeError: If an index is provided for a single qubit or if no index is provided for a
                qubit register.
            IndexError: If an index is provided that is out of bounds for the qubit register.
            ValueError: If the qubit is not allocated by this operation.
        """
        qubit_pos = self._get_qubit_pos(qubit, index)

        if self.coords is None:
            return None

        return self.coords.data[qubit_pos]

    @overload
    def get_qubit_id(self, qubit: SSAValue[QubitType], index: None = None) -> IntAttr | None: ...

    @overload
    def get_qubit_id(self, qubit: SSAValue[QubitRegType], index: int) -> IntAttr | None: ...

    def get_qubit_id(
        self, qubit: SSAValue[QubitType | QubitRegType], index: int | None = None
    ) -> IntAttr | None:
        """Find the id of a qubit allocated by this operation.

        Args:
            qubit: The SSA value of the qubit or qubit register to get the id of.
            index: If the qubit is a register, the index of the desired qubit within the register.

        Returns:
            The id attribute of the specified qubit, or None if this operation doesn't
            assign ids.

        Raises:
            TypeError: If an index is provided for a single qubit or if no index is provided for a
                qubit register.
            IndexError: If an index is provided that is out of bounds for the qubit register.
            ValueError: If the qubit is not allocated by this operation.
        """
        qubit_pos = self._get_qubit_pos(qubit, index)

        if self.ids is None:
            return None

        return self.ids.data[qubit_pos]


