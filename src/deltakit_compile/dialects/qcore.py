class SplitOp(IRDLOperation):
    """Split a qubit register into multiple smaller registers, maintaining the same qubit order as
    in the original register."""

    name = "qcore.split"

    _Q: ClassVar[IntConstraint] = MessageIntConstraint(
        IntVarConstraint("Qubit_Count", AnyInt()),
        "The number of qubits in input and output do not match.",
    )

    in_reg = operand_def(QubitRegType.constr(_Q))
    out_regs = var_result_def(SumOver(RangeOf(base(QubitRegType)), qubit_count, _Q))

    assembly_format = "`(` $in_reg `:` type($in_reg) `)` attr-dict `->` type($out_regs)"

    traits = traits_def(Pure(), NoQuantumEffect(), _SplitOpHasCanonicalizationPatternsTrait())

    def __init__(
        self, reg: SSAValue[QubitRegType], out_reg_types: Sequence[int | QubitRegType]
    ) -> None:
        reg_types = [QubitRegType(arg) if isinstance(arg, int) else arg for arg in out_reg_types]
        super().__init__(operands=(reg,), result_types=(reg_types,))


