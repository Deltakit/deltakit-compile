class _PauliEnum(BetterStrEnum):
    X = auto()
    Y = auto()
    Z = auto()

    def flipped(self) -> _PauliEnum:
        """Flip ``X`` and ``Z``, leaving ``Y`` unchanged."""
        match self:
            case _PauliEnum.X:
                return _PauliEnum.Z
            case _PauliEnum.Y:
                return _PauliEnum.Y
            case _PauliEnum.Z:
                return _PauliEnum.X


@irdl_attr_definition
class PauliAttr(AnyEnumAttribute[_PauliEnum]):
    """An Attribute for a Pauli Basis."""

    name = "qcore.pauli"

    def __init__(self, pauli: _PauliEnum | Literal["X", "Y", "Z"]):
        if not isinstance(pauli, _PauliEnum):
            pauli = _PauliEnum[pauli]
        super().__init__(pauli)

    def __mul__(self, other: PauliAttr) -> PauliAttr | None:
        """Multiplication of Paulis without sign:
        X * Y = Z, X * Z = Y, Y * Z = X,
        X * X = Y * Y = Z * Z = None"""
        if self == other:
            return None
        remaining = set(PauliAttr) - {self, other}
        # remaining must contain exactly the third Pauli; wrap back into a PauliAttr
        return remaining.pop()

    def flipped(self) -> PauliAttr:
        return PauliAttr(self.data.flipped())

    @classmethod
    def X(cls) -> PauliAttr:  # noqa: N802
        "An X Pauli Basis PauliAttr"
        return cls(_PauliEnum.X)

    @classmethod
    def Y(cls) -> PauliAttr:  # noqa: N802
        "A Y Pauli Basis PauliAttr"
        return cls(_PauliEnum.Y)

    @classmethod
    def Z(cls) -> PauliAttr:  # noqa: N802
        "A Z Pauli Basis PauliAttr"
        return cls(_PauliEnum.Z)

    @staticmethod
    def coerce(pauli: PauliAttr | Literal["X", "Y", "Z"]) -> PauliAttr:
        """Ensures the argument is returned as a PauliBasis."""
        if isinstance(pauli, PauliAttr):
            return pauli
        return PauliAttr(pauli)

    @classmethod
    def parse_optional_pauli_string(cls, parser: AttrParser) -> ArrayAttr[PauliAttr] | None:
        """Parses an uninterrupted sequence of `(X|Y|Z)*` without needing other attribute syntax,
        eg. ``XYZ`` is parsed into an ``ArrayAttr([PauliAttr.X(), PauliAttr.Y(), PauliAttr.Z()])``.
        This will raise a parsing error if the next token is an identifier that contains any
        non-pauli (not X, Y, or Z) characters.

        Args:
            parser: The parsing source.

        Returns:
            An ``ArrayAttr[PauliAttr]`` representation of the Pauli string if it could be parsed, or
            None if an identifier could not be parsed.
        """
        string = parser.parse_optional_identifier()
        if string is None:
            return None
        paulis = []
        for char in string:
            if char not in "XYZ":
                parser.raise_error(
                    "Expected a PauliString (that only contains X, Y, or Z, characters) but got "
                    f"'{string}'."
                )
            paulis.append(PauliAttr(_PauliEnum[char]))
        return ArrayAttr(paulis)

    @staticmethod
    def print_pauli_string(pauli_string: Iterable[PauliAttr], printer: Printer) -> None:
        """Prints an uninterrupted sequence of ``PauliAttr``s without needing other attribute
        syntax,
        eg. ``[PauliAttr.X(), PauliAttr.Y(), PauliAttr.Z()]`` is printed as ``XYZ``.

        Args:
            pauli_string: The paulis to print as a Pauli string.
            printer: The printer with which to print the Pauli string.
        """
        printer.print_list(pauli_string, lambda p: p.print_inner(printer), delimiter="")

    @staticmethod
    def is_valid_pauli_string(string: str) -> TypeGuard[Iterable[Literal["X", "Y", "Z"]]]:
        """Type-guard that checks if the provided string is a valid Pauli string."""
        return all(c in "XYZ" for c in string)

    def to_string(self) -> Literal["X", "Y", "Z"]:
        match self.data:
            case _PauliEnum.X:
                return "X"
            case _PauliEnum.Y:
                return "Y"
            case _PauliEnum.Z:
                return "Z"
        # This portion should be unreachable, but mypy does not realise it.
        msg = f"Found an unexpected {_PauliEnum.__name__} value: {self.data}."
        raise RuntimeError(msg)


Pauli: TypeAlias = PauliAttr | Literal["X", "Y", "Z"]
"""A PauliAttr or a str literal that can be coerced into a PauliAttr."""


