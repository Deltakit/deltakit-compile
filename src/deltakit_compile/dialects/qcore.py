class RecursiveQuantumEffect(QuantumEffect):
    """A trait that signals that an operation has the quantum side effects of its contained
    operations."""

    @override
    def get_effects(self, op: Operation) -> set[QuantumEffectInstance] | None:
        effects = set[QuantumEffectInstance]()
        for region in op.regions:
            for block in region.blocks:
                for child_op in block.ops:
                    child_effects = get_quantum_effects(child_op)
                    if child_effects is None:
                        return None
                    effects.update(child_effects)
        return effects


