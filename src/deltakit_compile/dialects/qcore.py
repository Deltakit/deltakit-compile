NpComplexMatrix: TypeAlias = np.ndarray[tuple[int, int], np.dtype[np.complex128]]


class GateAttribute(ParametrizedAttribute):
    """The base class for all gate attributes."""

    name = "qcore.gate.???"

    NP_FORMAT: ClassVar[np.dtype[np.complex128]] = np.dtype(np.complex128).newbyteorder("<")
    """The numpy format used to make and extract data from the ByteAttr that stores the matrix.
    Using newbyteorder overrides machine endianness to ensure consistency with xDSL."""

    @abstractmethod
    def get_unitary_matrix(self) -> NpComplexMatrix:
        """Returns the unitary matrix that defines this gate as a read-only numpy matrix (ndarray).
        This will be in big-endian form - see UnitaryGateAttr for details.

        Returns:
            A read only numpy matrix containing the big-endian unitary matrix for the gate
            represented by this attribute."""

    def get_qubit_count(self) -> int:
        """Returns the number of qubit operands this gates operates on."""
        matrix_shape = self.get_unitary_matrix().shape
        assert len(matrix_shape) == 2
        assert matrix_shape[0] == matrix_shape[1]
        qubit_count = math.log2(matrix_shape[0])
        assert qubit_count.is_integer()
        return int(qubit_count)

    def as_unitary_gate_attr(self) -> UnitaryGateAttr:
        """Returns this gate represented as a UnitaryGateAttr."""
        return UnitaryGateAttr.from_ndarray(self.get_unitary_matrix())

    def short_str(self) -> str:
        """Returns a short string that is suitable for error messages that should roughly identify
        this GateAttribute.

        Returns:
            A potentially lossy string representation of this gate.
        """
        return str(self)


@dataclass(frozen=True)
class GateConstraint(AttrConstraint[GateAttribute]):
    """Constrains an Attribute to being a GateAttribute with optional further constraint on the
    number of qubits the gate operates on.
    """

    qubits: IntConstraint = field(default_factory=AnyInt)

    @override
    def verify(
        self,
        attr: Attribute,
        constraint_context: ConstraintContext,
    ) -> None:
        BaseAttr(GateAttribute).verify(attr, constraint_context)
        assert isinstance(attr, GateAttribute)
        qubits = attr.get_qubit_count()
        self.qubits.verify(qubits, constraint_context)

    @override
    def variables(self) -> set[str]:
        return self.qubits.variables()

    @override
    def mapping_type_vars(
        self, type_var_mapping: Mapping[TypeVar, AttrConstraint | IntConstraint]
    ) -> AttrConstraint[GateAttribute]:
        return GateConstraint(self.qubits.mapping_type_vars(type_var_mapping))


@irdl_attr_definition
class UnitaryGateAttr(GateAttribute):
    """An attribute that can universally represent any quantum gate as a unitary matrix, to be used
    in qref and qssa gate ops. Not the most convenient representation for readability, but one that
    the named gates below can all be converted to and from, allowing us to, e.g., break an
    arbitrary gate down into multiple known gates that we can calculate stabiliser flows through.

    The format of an n-qubit unitary matrix assumes the vector is in C^(2**n) where the elements are
    the coefficients of the n-qubit basis states in the Z basis, and the bit strings for each
    element form the ascending binary numbers from 0 to (2**n)-1.

    This is the big-endian representation of the vector, and so matrix too, that is used across all
    unitary matrices within deltakit-compile.

    For a 3-qubit gate the vector would be the complex coefficients of:
        (
            |000>,
            |001>,
            |010>,
            |011>,
            |100>,
            |101>,
            |110>,
            |111>,
        )

    Attributes:
        name: This `Attribute`s fully qualified name
        matrix: The underlying storage for the unitary matrix that defines this gate.

    Args:
            matrix: A unitary matrix
    """

    name = "qcore.gate.unitary"

    matrix: DenseIntOrFPElementsAttr[ComplexType[Float64Type]] = param_def(
        ParamAttrConstraint[DenseIntOrFPElementsAttr[ComplexType[Float64Type]]].get(
            DenseIntOrFPElementsAttr,
            TensorType.constr(
                ComplexType.constr(Float64Type()),
                MessageConstraint(
                    ArrayOfConstraint(
                        RangeOf(
                            IntAttr.constr(TwoToThePowerOf(IntVarConstraint("I", AtLeast(1))))
                        ).of_length(2)
                    ),
                    "The dimensions of a unitary matrix must be 2**n by 2**n where n is the "
                    "number of qubits acted upon.",
                ),
            ),
            None,
        )
    )

    def __init__(
        self,
        matrix: DenseIntOrFPElementsAttr[ComplexType[Float64Type]]
        | Sequence[Sequence[ComplexNumberAttr[Float64Type] | complex | tuple[float, float]]],
    ):
        if not isinstance(matrix, DenseIntOrFPElementsAttr):
            matrix = UnitaryGateAttr._sequences_to_matrix(matrix)
        super().__init__(matrix)

    @classmethod
    def from_ndarray(
        cls, array: np.ndarray[tuple[int, int], np.dtype[np.number]]
    ) -> UnitaryGateAttr:
        """Produces a UnitaryGateAttr from a numpy ndarray.

        Args:
            array: a numpy ndarray containing the unitary matrix that defines the desired gate.

        Raises:
            ValueError: If the numpy array does not have exactly 2 dimensions.

        Returns:
            A UnitaryGateAttr representing the quantum gate specified by the given unitary matrix.
        """
        if len(array.shape) != 2:
            msg = f"Expected a unitary matrix array with 2 dimensions but got {len(array.shape)}."
            raise ValueError(msg)
        tensor_type = TensorType(ComplexType(Float64Type()), array.shape)
        data = DenseIntOrFPElementsAttr(
            tensor_type,
            BytesAttr(array.astype(cls.NP_FORMAT, copy=False).tobytes()),
            # tobytes() always makes a copy so we get a safe - immutable - version of the matrix
            # and astypes() need not make a copy if the format is already correct
        )
        return cls(data)

    @classmethod
    def from_u3(
        cls,
        theta: float | FloatAttr[Float64Type],
        phi: float | FloatAttr[Float64Type],
        lam: float | FloatAttr[Float64Type],
    ) -> UnitaryGateAttr:
        """Produces a UnitaryGateAttr representing a general single-qubit rotation parametrized by
        three angles (theta, phi, lambda). The three angles converted to radians represent
        (theta * pi, phi * pi, lambda * pi). This matches tsim/clifft's U3 convention.

        Args:
            theta: The first U3 angle, as a multiple of pi.
            phi: The second U3 angle, as a multiple of pi.
            lam: The third U3 angle, as a multiple of pi.

        Returns:
            A UnitaryGateAttr representing the U3(theta, phi, lambda) gate.
        """
        theta_rad = (theta.value.data if isinstance(theta, FloatAttr) else theta) * np.pi
        phi_rad = (phi.value.data if isinstance(phi, FloatAttr) else phi) * np.pi
        lam_rad = (lam.value.data if isinstance(lam, FloatAttr) else lam) * np.pi
        cos, sin = np.cos(theta_rad / 2), np.sin(theta_rad / 2)
        matrix = np.array(
            [
                [cos, -np.exp(1j * lam_rad) * sin],
                [np.exp(1j * phi_rad) * sin, np.exp(1j * (phi_rad + lam_rad)) * cos],
            ],
            dtype=cls.NP_FORMAT,
        )
        return cls.from_ndarray(matrix)

    @staticmethod
    def matrix_to_u3_angles(
        matrix: NpComplexMatrix, phase_tolerance: float = 1e-9
    ) -> tuple[float, float, float]:
        """Decomposes a single-qubit unitary matrix into U3 angles (theta, phi, lambda), each as a
        multiple of pi. The inverse of `from_u3`: `UnitaryGateAttr.from_u3(*angles)` reconstructs
        matrix up to global phase, for `angles = matrix_to_u3_angles(matrix)`.

        Any later cleanup of numerical noise in the angles (e.g. 0.5000000003 -> 0.5) is left to a
        lowering-time rounding step, not done here.

        Args:
            matrix: A 2x2 unitary matrix.
            phase_tolerance: Below this magnitude, a matrix entry is treated as exactly zero
                rather than as a numerically-noisy phase.

        Returns:
            A (theta, phi, lam) tuple, each a multiple of pi, such that U3(theta, phi, lam) equals
            matrix up to global phase.
        """
        a, b = complex(matrix[0, 0]), complex(matrix[0, 1])
        c, d = complex(matrix[1, 0]), complex(matrix[1, 1])
        theta_rad = 2 * math.atan2(abs(c), abs(a))

        # b and c both carry a factor of sin(theta_rad/2), so when that's ~0 their phase is
        # numerical noise; use d (which carries the reliable cos(theta_rad/2) factor) for lam
        # instead, with phi fixed to 0 (phi and lam are degenerate here, only their sum affects
        # the matrix).
        if abs(c) < phase_tolerance:
            delta = cmath.phase(a)
            phi_rad = 0.0
            lam_rad = cmath.phase(d) - delta
        # Symmetric case: a and d carry cos(theta_rad/2) ~ 0, so anchor on c instead, with phi
        # fixed to 0 (delta absorbs all of c's phase) and lam read off the reliable b.
        elif abs(a) < phase_tolerance:
            delta = cmath.phase(c)
            phi_rad = 0.0
            lam_rad = cmath.phase(-b) - delta
        else:
            delta = cmath.phase(a)
            phi_rad = cmath.phase(c) - delta
            lam_rad = cmath.phase(-b) - delta

        return theta_rad / math.pi, phi_rad / math.pi, lam_rad / math.pi

    def as_ndarray(self) -> NpComplexMatrix:
        """Returns the unitary matrix as a read-only numpy ndarray.

        Returns:
            A 2**n by 2**n array, where n is the number of qubits this gate operates on.
        """
        array = np.frombuffer(self.matrix.data.data, dtype=self.NP_FORMAT)
        array.flags.writeable = False
        # Casting the shape is guaranteed safe by the constraints on self.matrix
        return array.reshape(cast(tuple[int, int], self.matrix.type.get_shape()))

    @override
    def verify(self) -> None:
        unitary = self.as_ndarray()
        expected_identity = unitary @ unitary.conjugate().T
        norm = np.linalg.norm(
            expected_identity - np.identity(unitary.shape[0], dtype=np.complex128)
        )
        if not math.isclose(norm, 0, rel_tol=1e-10, abs_tol=1e-10):
            msg = "The given matrix, U, is not unitary since | U @ dag(U) - I | != 0."
            raise VerifyException(msg)

    @override
    def get_unitary_matrix(self) -> NpComplexMatrix:
        return self.as_ndarray()

    @override
    def as_unitary_gate_attr(self) -> UnitaryGateAttr:
        return self

    @override
    def short_str(self) -> str:
        return f"{self.name}<... {'x'.join(map(str, self.as_ndarray().shape))}>"

    @staticmethod
    def _sequences_to_matrix(
        argument: Sequence[
            Sequence[ComplexNumberAttr[Float64Type] | complex | tuple[float, float]]
        ],
    ) -> DenseIntOrFPElementsAttr[ComplexType[Float64Type]]:
        """Convert nested Sequences of complex float tuples into a DenseIntOrFPElementsAttr with the
        correct type.

        Arguments:
            argument: A sequence of sequences of elements of a complex matrix. Each inner sequence
                must have the same length and this must be equal to the length of the outer
                sequence, ie the matrix must be square. Each element can be a complex number, a
                tuple of two floats interpreted as ``(real, imaginary)``, or an xDSL attribute for a
                Complex fp64+fp64 number.

        Raises:
            ValueError: if the argument does not form a square matrix.

        Returns:
            An xDSL attribute that stores the matrix densely along with its shape/type as as a
            TensorType.

        """

        lengths = {len(row) for row in argument}
        if len(lengths) != 1 or lengths.pop() != len(argument):
            msg = (
                "Argument does not form a square matrix, expected each row to be the same "
                f"length as the number of rows, but argument was: {argument}"
            )
            raise ValueError(msg)

        def extract_values(
            value: ComplexNumberAttr[Float64Type] | complex | tuple[float, float],
        ) -> tuple[float, float]:
            if isinstance(value, ComplexNumberAttr):
                return (value.real.data, value.imag.data)
            if isinstance(value, complex):
                return (value.real, value.imag)
            return value

        flattened_data = [extract_values(value) for row in argument for value in row]
        return DenseIntOrFPElementsAttr.from_list(
            TensorType(ComplexType(Float64Type()), [len(argument)] * 2), flattened_data
        )

    @classmethod
    def coerce(
        cls,
        arg: UnitaryGateAttr
        | DenseIntOrFPElementsAttr[ComplexType[Float64Type]]
        | Sequence[Sequence[ComplexNumberAttr[Float64Type] | tuple[float, float]]]
        | np.ndarray[tuple[int, int], np.dtype[np.number]],
    ) -> UnitaryGateAttr:
        """Ensures the argument is returned as a ``UnitaryGateAttr``.

        Arguments:
            arg: An argument to convert (if required) into a ``UnitaryGateAttr``

        Returns:
            A ``UnitaryGateAttr`` based on the matrix defined by ``arg``.
        """
        if isinstance(arg, UnitaryGateAttr):
            return arg
        if isinstance(arg, np.ndarray):
            return cls.from_ndarray(arg)
        return UnitaryGateAttr(arg)

    @classmethod
    def constr(
        cls,
        *,
        qubits: IntConstraint | None = None,
        dimension: IntConstraint | int | None = None,
    ) -> AttrConstraint[UnitaryGateAttr]:
        """Constructs a constraint on a UnitaryGateAttr that constrains the number of
        qubits it refers to, and/or the dimension size of the matrix.

        Arguments:
            qubits: An optional constraint on the number of qubits operated on by a
                ``UnitaryGateAttr`` gate.
            dimension: An optional constraint on the size of the unitary matrix.

        Returns:
            A constraint that ensure an ``Attribute`` is a ``UnitaryGateAttr`` that operates on
            ``qubit`` qubits and has a unitary matrix shape of ``dimension`` by ``dimension``.
        """
        int_attr_constraint = AnyAttr()
        if qubits is not None:
            int_attr_constraint &= MessageConstraint(
                IntAttr.constr(TwoToThePowerOf(qubits)),
                "The number of qubits, n, as determined by the size of the unitary gate matrix "
                "does not satisfy its constraint.",
            )
        if dimension is not None:
            int_attr_constraint &= MessageConstraint(
                IntAttr.constr(dimension),
                "The size of the unitary gate matrix does not satisfy its constraint.",
            )

        return ParamAttrConstraint.get(
            UnitaryGateAttr,
            ParamAttrConstraint.get(
                DenseIntOrFPElementsAttr,
                TensorType.constr(shape=ArrayOfConstraint(int_attr_constraint)),
                None,
            ),
        )

    @override
    @classmethod
    def parse_parameters(cls, parser: AttrParser) -> Sequence[Attribute]:
        """Parse the parameters of a ``UnitaryGateAttr`` in the form:
        ```
        <[[(1.0, 2.0), (...), ...], [...], ...]>
        ```

        Arguments:
            parser: The parser from which to parse the parameters of a ``UnitaryGateAttr``.

        Returns:
            A sequence that contains just the ``DenseIntOrFPElementsAttr[ComplexType[Float64Type]]``
            that parametrises this attribute.
        """
        start_position = parser.pos

        def parse_complex() -> tuple[float, float]:
            with parser.in_parens():
                real = parse_float64(parser)
                parser.parse_punctuation(",")
                imag = parse_float64(parser)
            return real, imag

        def parse_row() -> Sequence[tuple[float, float]]:
            return parser.parse_comma_separated_list(parser.Delimiter.SQUARE, parse_complex)

        with parser.in_angle_brackets():
            values = parser.parse_comma_separated_list(parser.Delimiter.SQUARE, parse_row)

        try:
            matrix = UnitaryGateAttr._sequences_to_matrix(values)
        except ValueError:
            parser.raise_error(
                "Could not parse values as a square matrix of complex floats.",
                start_position,
                parser.pos,
            )
        return (matrix,)

    @override
    def print_parameters(self, printer: Printer) -> None:
        """Print the parameters of this ``UnitaryGateAttr`` in the form:
        ```
        <[[(1.0, 2.0), (...), ...], [...], ...]>
        ```

        Arguments:
            printer: The printer with which to print.
        """

        def print_complex(value: tuple[float, float]) -> None:
            real, imag = value
            with printer.in_parens():
                printer.print_string(float64_to_string(real))
                printer.print_string(", ")
                printer.print_string(float64_to_string(imag))

        def print_row(row: tuple[tuple[float, float], ...]) -> None:
            with printer.in_square_brackets():
                printer.print_list(row, print_complex)

        with printer.in_angle_brackets():
            flat_values = self.matrix.get_values()
            rows = self.matrix.type.get_shape()[0]
            cols = self.matrix.type.get_shape()[1]
            with printer.in_square_brackets():
                for r in range(rows):
                    row = flat_values[r * cols : (r + 1) * cols]
                    if r:
                        printer.print_string(", ")
                    print_row(row)


class _GateOption(BetterStrEnum):
    """An Enum that defines the different options ``BaseGateAttributes`` could have."""

    SQRT = "sqrt"
    """Take the principal square root of the gate.
    While there can be multiple square roots for a gate, one is considered the principal one and is
    explicitly defined as such per gate that accepts this option."""
    DAG = "dag"
    """Take the transpose of the conjugate of the gate.
    This flips the signs of all the imaginary parts of each element, then transposes that result."""


@irdl_attr_definition
class GateOptionAttr(AnyEnumAttribute[_GateOption], use_values=True):
    """An ``Attribute`` for differentiating between variants of ``StandardGateAttribute``s"""

    name = "qcore.gate_option"

    @classmethod
    def constr_array(
        cls, *, one_of: Sequence[Sequence[_GateOption]], gate_name: str
    ) -> AttrConstraint[ArrayAttr[GateOptionAttr]]:
        options_str = ", ".join(
            [f"<{', '.join([str(part) for part in option])}>" for option in one_of]
        )
        return MessageConstraint(
            AnyOf(
                tuple(
                    EqAttrConstraint(ArrayAttr([cls(part) for part in option])) for option in one_of
                )
            ),
            f"Only the following options are allowed for a '{gate_name}': {options_str}",
        )


def _make_matrix(
    matrix: Sequence[Sequence[complex | float | int]] | NpComplexMatrix,
) -> NpComplexMatrix:
    """Returns a read only np ndarray of the given input. Used at import time to generate the
    standard gates' unitary matrices."""
    array = np.array(matrix, dtype=GateAttribute.NP_FORMAT, copy=True)
    array.flags.writeable = False
    assert len(array.shape) == 2
    # Static checks cannot work the shape of the array to ensure it is a matrix, so cast it instead.
    return cast(NpComplexMatrix, array)


class StandardGateAttribute(GateAttribute):
    """Base class for collection of standard gates attributes.
    This should not be used to make a semantic judgement on the meaning of a gate."""

    @property  # This must be a parameter of the ParameterizedAttribute
    @abstractmethod
    def options(self) -> ArrayAttr[GateOptionAttr]: ...

    @override
    @classmethod
    def parse_parameters(cls, parser: AttrParser) -> tuple[ArrayAttr[GateOptionAttr]]:
        """Parse the parameters of a gate that has variants in the form:
        ```
            (`<` ( plain(GateOptionAttr) (`,` plain(GateOptionAttr) )* )? `>`)?
        ```

        Arguments:
            parser: The parser to parse from.

        Returns:
            A ``tuple`` containing an ``ArrayAttr`` that contains the parsed ``GateOptionAttrs``.

        """

        options = parser.parse_optional_comma_separated_list(
            parser.Delimiter.ANGLE, lambda: GateOptionAttr.parse_inner(parser)
        )
        return (ArrayAttr(options or []),)

    @override
    def print_parameters(self, printer: Printer) -> None:
        """Print the parameters of this gate in the form:
        ```
            (`<` plain(GateOptionAttr) (`,` plain(GateOptionAttr) )* `>`)?
        ```

        Arguments:
            printer: The printer with which to print.
        """
        if len(self.options):
            with printer.in_angle_brackets():
                printer.print_list(self.options, lambda o: o.print_inner(printer))


