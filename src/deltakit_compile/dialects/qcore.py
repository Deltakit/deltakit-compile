@irdl_attr_definition
class QubitPauliStateAttr(ParametrizedAttribute):
    """The representation of a Pauli state on a single qubit.

    This must be attached to an op or attribute with a representation of qubits (e.g. a
    qstruct.circuit with !qcore.qubit arguments) to be meaningful, as its index refers to the index
    of a qubit within the parent (treated as if all the parent's qubits are packed into a single
    register)."""

    name = "qcore.pauli_state"

    pauli_state: PauliAttr
    index: IntAttr = param_def(IntAttrConstraint(AtLeast(0)))

    def __init__(
        self,
        pauli_state: Pauli,
        index: IntAttr | int,
    ):
        super().__init__(PauliAttr.coerce(pauli_state), IntAttr.get(index))

    @classmethod
    def _fast_create(cls, pauli_state: PauliAttr, index: IntAttr) -> QubitPauliStateAttr:
        """Bypass xDSL __init__/verify for internal use when inputs are known to be valid."""
        obj = object.__new__(cls)
        object.__setattr__(obj, "pauli_state", pauli_state)
        object.__setattr__(obj, "index", index)
        return obj

    def sort_key(self) -> int:
        """Get a sortable value from this QubitPauliStateAttr for use in a list of qubit states.
        By using just the qubit index and sorting with the strictly_increasing option we ensure that
        the qubits referred to by each QubitPauliStateAttr within one Pauli string are unique and in
        a canonical order."""
        return self.qubit_index

    @property
    def qubit_index(self) -> StateQubitIndex:
        """Get the (non-global) index of the qubit this qubit state refers to."""
        return self.index.data

    @classmethod
    def parse_qubit_state(cls, parser: AttrParser) -> tuple[PauliAttr, IntAttr] | None:
        """Parse the internal attributes of a QubitPauliStateAttr.

        Parses things like:
            X0
            Z30
        """
        state_str = parser.parse_optional_identifier_or_str_literal()
        if state_str is None:
            return None
        if (match := re.match(pattern := "(X|Y|Z)([0-9]+)", state_str)) is None:
            parser.raise_error(
                f"Expected {QubitPauliStateAttr.name} in the form {pattern}, got '{state_str}'"
            )
        state = PauliAttr(cast(Literal["X", "Y", "Z"], match.group(1)))
        index = IntAttr(int(match.group(2)))
        return state, index

    @override
    @classmethod
    def parse_parameters(cls, parser: AttrParser) -> list[Attribute]:
        with parser.in_angle_brackets():
            return list(
                parser.expect(lambda: cls.parse_qubit_state(parser), "Expected a Pauli State")
            )

    def print_qubit_state(self, printer: Printer) -> None:
        """Print the internal attributes of a QubitPauliStateAttr."""
        self.pauli_state.print_inner(printer)
        printer.print_int(self.qubit_index)

    @override
    def print_parameters(self, printer: Printer) -> None:
        with printer.in_angle_brackets():
            self.print_qubit_state(printer)


@irdl_attr_definition
class PauliStringAttr(PlainParsableParameterizedAttribute):
    """A single Pauli string consisting of multiple qubits, each with a Pauli State.

    Unlisted qubits can be assumed to have the 'I' state. This must be attached to an op or
    attribute with a representation of qubits (e.g. a qstruct.circuit with !qcore.qubit arguments)
    to be meaningful, as its qubit states refer to the indices of qubits within the parent (treated
    as if all the parent's qubits are packed into a single register). The qubit states are stored
    sorted by qubit index and each qubit index appears at most once."""

    name = "qcore.pauli_string"

    qubit_states: ArrayAttr[QubitPauliStateAttr] = param_def(
        AllOf(
            (
                MessageConstraint(
                    ArrayOfConstraint(
                        SetOf(RangeOf(base(QubitPauliStateAttr)), lambda q: q.index.data)
                    ),
                    "Each qubit in a Pauli string may only have one Pauli state.",
                ),
                MessageConstraint(
                    ArrayOfConstraint(
                        SortedRangeOf(
                            RangeOf(base(QubitPauliStateAttr)), QubitPauliStateAttr.sort_key
                        )
                    ),
                    "Qubit states must be ordered by their qubit index.",
                ),
            )
        ),
    )
    length: IntAttr = param_def(
        IntAttr.constr(
            MessageIntConstraint(AtLeast(1), "A Pauli string must be on at least 1 qubit.")
        )
    )

    def __init__(
        self,
        qubit_states: (
            ArrayAttr[QubitPauliStateAttr]
            | Iterable[QubitPauliStateAttr | tuple[Pauli, IntAttr | int]]
        ),
        length: IntAttr | int,
    ):
        if isinstance(qubit_states, ArrayAttr):
            states = sorted(qubit_states.data, key=QubitPauliStateAttr.sort_key)
        else:
            states = sorted(
                [
                    (s if isinstance(s, QubitPauliStateAttr) else QubitPauliStateAttr(*s))
                    for s in qubit_states
                ],
                key=QubitPauliStateAttr.sort_key,
            )
        super().__init__(ArrayAttr(states), IntAttr.get(length))

    @override
    def verify(self):
        """Verify the qubit IDs used in the qubit states are all valid within the pauli string's
        declared length."""
        length = self.length.data
        invalid_qubit_indices = [
            qs.qubit_index for qs in self.qubit_states.data if qs.qubit_index >= length
        ]
        if len(invalid_qubit_indices) > 0:
            msg = (
                f"{self.name} refers to qubit indices {invalid_qubit_indices} that are beyond its "
                f"length of {length}"
            )
            raise VerifyException(msg)

    @classmethod
    def _fast_create(cls, sorted_states: list[QubitPauliStateAttr], length: IntAttr) -> Self:
        """Bypass xDSL __init__/verify for internal use when inputs are already valid and sorted."""
        arr = object.__new__(ArrayAttr)
        object.__setattr__(arr, "data", tuple(sorted_states))
        obj = object.__new__(cls)
        object.__setattr__(obj, "qubit_states", arr)
        object.__setattr__(obj, "length", length)
        return obj

    @classmethod
    def constr(cls, length: IntConstraint) -> AttrConstraint[PauliStringAttr]:
        """Constructs a constraint on a PauliStringAttr that constrains its length."""
        return ParamAttrConstraint.get(PauliStringAttr, None, IntAttr.constr(length))

    @classmethod
    def identity(cls, length: int) -> Self:
        """Get an identity Pauli string (with no qubits in non-identity states)."""
        return cls._fast_create([], IntAttr(length))

    def resize(self, new_length: int) -> PauliStringAttr:
        """Return this Pauli string with a new length and unchanged qubit indices."""
        if new_length < 1:
            msg = "A Pauli string must be on at least 1 qubit."
            raise ValueError(msg)
        if self.qubit_states and self.get_max_qubit_index() >= new_length:
            msg = (
                f"Cannot resize Pauli string to length {new_length} because it uses qubit index "
                f"{self.get_max_qubit_index()}."
            )
            raise ValueError(msg)
        return PauliStringAttr._fast_create(list(self.qubit_states), IntAttr(new_length))

    @staticmethod
    def repeat(pauli: Pauli, length: int) -> PauliStringAttr:
        """Get a Pauli string with the given Pauli on every qubit."""
        # Use _fast_create since we know we create the qubit states in sorted order.
        pauli_attr = PauliAttr.coerce(pauli)
        return PauliStringAttr._fast_create(
            [
                QubitPauliStateAttr._fast_create(pauli_attr, IntAttr(index))
                for index in range(length)
            ],
            IntAttr(length),
        )

    def sort_key(self) -> tuple[int, ...]:
        """Get a sortable value from this PauliStringAttr for use in a list of Pauli strings.
        By sorting by the (already sorted) qubit indices of the string's qubit states, and then the
        Pauli states, we ensure there is a canonical representation of an array of Pauli strings and
        that it cannot contain duplicate Pauli strings, if required."""
        return (
            self.length.data,
            *(state.qubit_index for state in self.qubit_states),
            *(ord(state.pauli_state.data) for state in self.qubit_states),
        )

    def __iter__(self) -> Iterator[PauliAttr | None]:
        """Iterate over the Pauli states of the qubits in this Pauli string, in order of qubit
        index, including qubits that are in the identity state (yielding None for them)."""
        qubit_states_iter = iter(self.qubit_states)
        next_qubit_state = next(qubit_states_iter, None)
        for index in range(self.length.data):
            if next_qubit_state is not None and next_qubit_state.qubit_index == index:
                yield next_qubit_state.pauli_state
                next_qubit_state = next(qubit_states_iter, None)
            else:
                yield None

    def get_qubit_indices(self) -> set[StateQubitIndex]:
        """Get the (non-global) indices of the qubits this Pauli string refers to."""
        return {state.qubit_index for state in self.qubit_states}

    def get_index_to_pauli(self) -> dict[StateQubitIndex, PauliAttr]:
        """Get a mapping from the (non-global) indices of the qubits with non-identity Pauli states
        in this Pauli string to their Pauli states."""
        return {state.qubit_index: state.pauli_state for state in self.qubit_states}

    def get_max_qubit_index(self) -> StateQubitIndex:
        """Get the (non-global) maximum index of the qubits with non-identity Pauli states in this
        Pauli string. PauliStringAttr qubit states are guaranteed to be ordered by verify method."""
        return self.qubit_states.data[-1].index.data if self.qubit_states else I_STATE_INDEX

    def get_min_qubit_index(self) -> StateQubitIndex:
        """Get the (non-global) minimum index of the qubits with non-identity Pauli states in this
        Pauli string. PauliStringAttr qubit states are guaranteed to be ordered by verify method."""
        return self.qubit_states.data[0].index.data if self.qubit_states else I_STATE_INDEX

    def get_weight(self) -> int:
        """Return the weight (number of non-identity Pauli states present) of the Pauli string."""
        return len(self.qubit_states)

    def is_identity(self) -> bool:
        """Check whether the Pauli string corresponds to the identity Pauli string."""
        return not self.qubit_states.data

    def commutes(self, other: PauliStringAttr) -> bool:
        """Check whether two equal length Pauli strings commute."""
        if self.length.data != other.length.data:
            msg = (
                "Cannot check whether Pauli strings of differing lengths commute "
                f"({self.length.data} != {other.length.data})"
            )
            raise ValueError(msg)

        index_to_pauli_1 = self.get_index_to_pauli()
        index_to_pauli_2 = other.get_index_to_pauli()

        common_support = self.get_qubit_indices() & other.get_qubit_indices()

        num_anticommuting_paulis = 0
        for index in common_support:
            if index_to_pauli_1[index] != index_to_pauli_2[index]:
                num_anticommuting_paulis += 1

        return num_anticommuting_paulis % 2 == 0

    def __mul__(self, other: PauliStringAttr) -> PauliStringAttr:
        """Returns Pauli product of two equal length Pauli strings up to a sign, as
        PauliStringAttr."""

        if self.length.data != other.length.data:
            msg = (
                "Cannot multiply Pauli strings of differing lengths "
                f"({self.length.data} != {other.length.data})"
            )
            raise ValueError(msg)

        # Short-circuiting: identity on either side
        if self.is_identity():
            return other
        if other.is_identity():
            return self

        # Merge-scan over the sorted qubit states.
        i = j = 0
        result: list[QubitPauliStateAttr] = []
        while i < len(self.qubit_states) and j < len(other.qubit_states):
            qb1 = self.qubit_states.data[i]
            qb2 = other.qubit_states.data[j]
            if qb1.qubit_index == qb2.qubit_index:
                pauli_prod = qb1.pauli_state * qb2.pauli_state
                if pauli_prod is not None:
                    result.append(QubitPauliStateAttr._fast_create(pauli_prod, qb1.index))
                i += 1
                j += 1
            elif qb1.qubit_index < qb2.qubit_index:
                result.append(qb1)
                i += 1
            else:
                result.append(qb2)
                j += 1

        # Append remaining qubit states from either string (already sorted)
        result.extend(self.qubit_states.data[i:])
        result.extend(other.qubit_states.data[j:])

        # The result is already sorted by construction.
        return PauliStringAttr._fast_create(result, self.length)

    def get_local_pauli_string(self, indices: list[StateQubitIndex]) -> PauliStringAttr:
        """Compute the restriction of this Pauli string to the given indices, re-indexed by relative
        order in the list of indices.

        Args:
            indices: The indices to restrict to, in the order in which the qubits should be
                re-indexed in the resulting local Pauli string.

        Returns:
            A new PauliStringAttr containing the qubit states of this Pauli string on the given
            indices, with the qubit indices re-labelled to be in the range [0, len(indices))
            according to their order in the input list of indices.

        Raises:
            ValueError: If the local Pauli string would be longer than its origin Pauli string.

        Example:
            On the Pauli string X0 Y1 Z2 : 3 with indices [2,0], the result is the Pauli string
            Z0 X1 : 2.
        """
        if self.length.data < len(indices):
            msg = "Cannot create a local Pauli string longer than its origin Pauli string."
            raise ValueError(msg)
        if any(i >= self.length.data for i in indices):
            msg = (
                "Cannot create a local Pauli string using indices of qubits beyond the length "
                "of the origin Pauli string."
            )
            raise ValueError(msg)

        index_to_pauli = self.get_index_to_pauli()

        # Generate the final list of Pauli states in sorted order
        new_states = [
            QubitPauliStateAttr._fast_create(index_to_pauli[global_index], IntAttr(local_index))
            for local_index, global_index in enumerate(indices)
            if global_index in index_to_pauli
        ]

        # Since new_states is already sorted and validated, we can use _fast_create
        return PauliStringAttr._fast_create(new_states, IntAttr(len(indices)))

    def with_updated_local_pauli_string(
        self, local_pauli_string: PauliStringAttr, indices: list[StateQubitIndex]
    ) -> PauliStringAttr:
        """Get a new Pauli string with the local Pauli string on the given indices updated to the
        given local Pauli string, and the same Pauli states as this Pauli string on all other
        indices.

        Args:
            local_pauli_string: The local Pauli string to update the given indices with.
            indices: The indices to update in the Pauli string.

        Returns:
            A copy of this Pauli string with the qubit states on the given indices replaced with
            those of the given local Pauli string.

        Raises:
            ValueError: If the local Pauli string contains (non-identity) qubit states on indices
                outside [0, len(indices)).

        Example:
            On the Pauli string X0 Y1 Z2: 3, with local_pauli_string Y0 Z1 : 2 and indices [2,0],
            the result is Z0 Y1 Y2: 3.
        """
        if local_pauli_string.get_max_qubit_index() >= len(indices):
            msg = f"The Pauli string {local_pauli_string} is not local to the indices {indices}."
            raise ValueError(msg)

        local_index_to_pauli = local_pauli_string.get_index_to_pauli()
        new_index_to_pauli = self.get_index_to_pauli()
        for local_index, new_index in enumerate(indices):
            if local_index in local_index_to_pauli:
                new_index_to_pauli[new_index] = local_index_to_pauli[local_index]
            elif new_index in new_index_to_pauli:
                # Local Pauli string is identity on this index, so make new Pauli string identity
                del new_index_to_pauli[new_index]

        # Create the new Paulis in sorted order so we can use _fast_create
        sorted_indices = sorted(new_index_to_pauli.keys())
        return PauliStringAttr._fast_create(
            [
                QubitPauliStateAttr._fast_create(new_index_to_pauli[index], IntAttr(index))
                for index in sorted_indices
            ],
            self.length,
        )

    def permute_indices(self, permutation: Sequence[int]) -> PauliStringAttr:
        """Permute the qubit indices of this Pauli string.

        The permutation is given as a sequence of integers p such that an input index i maps to the
        output index p[i].
        """
        return PauliStringAttr(
            [(qb.pauli_state, permutation[qb.qubit_index]) for qb in self.qubit_states], self.length
        )

    def map_indices(
        self, index_map: Mapping[int, int], length: int | None = None
    ) -> PauliStringAttr:
        """Map the qubit indices of this Pauli string.

        As an example, calling that method on a Pauli string of length 5 representing ``Z0Z1Z2``
        with the mapping ``{0: 2, 1: 3, 2: 0}`` and with the default ``length`` parameter will
        return a Pauli string of length 5 representing ``Z1Z2Z3``.

        Args:
            index_map: a map from qubit indices in ``self`` to qubit indices in the returned Pauli
                string.
            length: if provided, the length of the resulting Pauli string. Defaults to ``None``
                which means the length will be computed automatically as
                ``max(self.length, <max index in resulting Pauli> + 1)``.

        Returns:
            A new ``PauliStringAttr`` instance with mapped qubit indices.
        """
        if length is None:
            length = max(
                self.length.data, max(index_map[qb.qubit_index] for qb in self.qubit_states) + 1
            )
        return PauliStringAttr(
            [(qb.pauli_state, index_map[qb.qubit_index]) for qb in self.qubit_states], length
        )

    def shift_qubit_indices(
        self, idx_shift: int, *, new_length: int | None = None
    ) -> PauliStringAttr:
        """Return a new Pauli string with all qubit indices shifted by ``idx_shift``.

        Args:
            idx_shift: The integer offset to add to every qubit index in this Pauli string.
                May be negative. If shifting would produce any negative qubit index, or a qubit
                index greater than the length of the Pauli string, an error is raised.
            new_length: A new length to give the output Pauli string.

        Returns:
            A new :class:`PauliStringAttr` with shifted indices. If this is the identity Pauli
            string, returns ``self``.

        Raises:
            ValueError: If applying ``idx_shift`` would produce a negative qubit index.
        """
        new_length = self.length.data if new_length is None else new_length
        if self.is_identity():
            return PauliStringAttr.identity(new_length)
        if idx_shift + self.get_min_qubit_index() < 0:
            msg = "The shift given would produce qubit states with negative indices."
            raise ValueError(msg)
        if idx_shift + self.get_max_qubit_index() > new_length:
            msg = (
                "The shift given would produces qubit states with indices greater than the length "
                "of the Pauli string."
            )
            raise ValueError(msg)

        return PauliStringAttr(
            [(q.pauli_state, q.qubit_index + idx_shift) for q in self.qubit_states], new_length
        )

    def flipped(self) -> PauliStringAttr:
        """Return a new Pauli string with all ``X`` and ``Z`` Paulis flipped."""
        return PauliStringAttr(
            [(q.pauli_state.flipped(), q.qubit_index) for q in self.qubit_states], self.length
        )

    @classmethod
    def parse_qubit_pauli_states(cls, parser: AttrParser) -> ArrayAttr[QubitPauliStateAttr]:
        """Parse the qubit pauli states of a PauliStringAttr.

        Parses things like:
            I
            X0 X1
            X3 Z10
        """
        states: list[QubitPauliStateAttr] = []
        if parser.parse_optional_characters("I"):
            return ArrayAttr([])

        while (state := QubitPauliStateAttr.parse_qubit_state(parser)) is not None:
            states.append(QubitPauliStateAttr(*state))
        return ArrayAttr(states)

    @override
    @classmethod
    def parse_inner_parameters(
        cls, parser: AttrParser
    ) -> tuple[ArrayAttr[QubitPauliStateAttr], IntAttr]:
        """Parse all the internal attributes of a PauliStringAttr.

        Parses things like:
            I : 10
            X0 X1 : 2
            X3 Z10 : 12
        """
        states = cls.parse_qubit_pauli_states(parser)
        parser.parse_punctuation(":")
        length = parser.parse_integer(allow_boolean=False, allow_negative=False)
        return (states, IntAttr(length))

    def print_qubit_pauli_states(self, printer: Printer) -> None:
        """Print the qubit pauli states of a PauliStringAttr."""
        if len(self.qubit_states) == 0:
            printer.print_string("I")
        else:
            printer.print_list(
                self.qubit_states, lambda state: state.print_qubit_state(printer), delimiter=" "
            )

    @override
    def print_inner(self, printer: Printer) -> None:
        """Print all the internal attributes of a PauliStringAttr."""
        self.print_qubit_pauli_states(printer)
        printer.print_string(" : ")
        printer.print_int(self.length.data)

    def as_str(self) -> str:
        """A string representation of the Pauli string, for error messages.
        For example: "X0 Z1 Y2".
        Note that the length of the Pauli string is not printed."""
        str_io = StringIO()
        printer = Printer(stream=str_io)
        self.print_qubit_pauli_states(printer)
        return str_io.getvalue()

    @staticmethod
    def collection_as_str(pauli_strings: Iterable[PauliStringAttr]) -> str:
        """A string representation of a collection of pauli strings, for error messages.
        For example: "[X0 Z1 Y2, Z4, Y10]".
        Note that the lengths of each `PauliStringAttr` may not be the same and are not printed."""
        strings = sorted(pauli_strings, key=PauliStringAttr.sort_key)
        str_io = StringIO()
        printer = Printer(stream=str_io)
        with printer.in_square_brackets():
            printer.print_list(
                strings,
                lambda pauli_string: pauli_string.print_qubit_pauli_states(printer),
                delimiter=", ",
            )
        return str_io.getvalue()


@irdl_attr_definition
class QubitCoordinateAttr(ParametrizedAttribute):
    """An Attribute for the coordinate of a qubit."""

    name = "qcore.qubit_coordinate"

    values: ArrayAttr[FloatAttr[Float64Type]] = param_def(
        ArrayOfConstraint(
            RangeOf(base(FloatAttr[Float64Type])).of_length(
                MessageIntConstraint(
                    AtLeast(1),
                    "Coordinates must have at least 1 dimension.",
                )
            )
        )
    )

    def __init__(self, values: Iterable[FloatAttr[Float64Type] | float]):
        super().__init__(
            ArrayAttr(
                [
                    val if isinstance(val, FloatAttr) else FloatAttr(float(val), Float64Type())
                    for val in values
                ]
            )
        )

    def __len__(self) -> int:
        """Returns the number of dimensions this coordinate has."""
        return len(self.values)

    def __iter__(self) -> Iterator[FloatAttr[Float64Type]]:
        """Returns each value in the coordinate as a FloatAttr"""
        return iter(self.values)

    @property
    def data(self) -> tuple[float, ...]:
        """Returns a tuple of each value in the coordinate as a float"""
        return tuple(value.value.data for value in self)

    @classmethod
    def coerce(
        cls, arg: QubitCoordinateAttr | Iterable[FloatAttr[Float64Type] | float]
    ) -> QubitCoordinateAttr:
        """Ensures the argument is returned as a QubitCoordinateAttr."""
        return arg if isinstance(arg, QubitCoordinateAttr) else QubitCoordinateAttr(arg)

    @classmethod
    def constr(cls, dimensions: IntConstraint) -> AttrConstraint[QubitCoordinateAttr]:
        """Constructs a constraint on a QubitCoordinateAttr that constrains the number of
        dimensions."""
        return ParamAttrConstraint(
            QubitCoordinateAttr, (ArrayOfConstraint(RangeOf(AnyAttr()).of_length(dimensions)),)
        )

    @override
    @classmethod
    def parse_parameters(cls, parser) -> Sequence[Attribute]:
        """Parse the parameters of a QubitCoordinateAttr in the form: (1, 2.0, -4.4)"""
        with parser.in_parens():
            values = parser.parse_comma_separated_list(
                parser.Delimiter.NONE, lambda: parse_float64(parser)
            )

        return (ArrayAttr([FloatAttr(float(value), Float64Type()) for value in values]),)

    @override
    def print_parameters(self, printer: Printer) -> None:
        """Print the parameters of this QubitCoordinateAttr in the form: (1.0, 2.0, -4.4)"""
        with printer.in_parens():
            printer.print_list(
                self.data, lambda f: printer.print_string(float64_to_string(float(f)))
            )


@irdl_custom_directive
class AllocQubitPropsDirective(CustomDirective):
    """Custom printing and parsing directive for the optional properties of AllocQubitOp.

    Parses and prints the `coords` and `ids` keyword properties in the form::

        coords = [(0.0, 1.0), (2.0, 3.0)], ids = [0, 1]
        ids = [0, 1], coords = [(0.0, 1.0), (2.0, 3.0)]
        coords = [(0.0, 1.0), (2.0, 3.0)]
        ids = [0, 1]

    Keywords may appear in either order when parsing but are always printed in the canonical
    order: coords first, then ids.
    """

    coords_attr: AttributeVariable
    ids_attr: AttributeVariable

    @override
    def parse(self, parser: Parser, state: ParsingState) -> bool:
        parsed_coords = False
        parsed_ids = False

        def _parse_one() -> bool:
            nonlocal parsed_coords, parsed_ids

            if not parsed_coords and parser.parse_optional_keyword("coords"):
                parser.parse_punctuation("=")
                coordinate_values = parser.parse_comma_separated_list(
                    parser.Delimiter.SQUARE, lambda: QubitCoordinateAttr.parse_parameters(parser)
                )
                qubit_coordinates = [QubitCoordinateAttr.new(coord) for coord in coordinate_values]
                self.coords_attr.set(state, ArrayAttr(qubit_coordinates))
                parsed_coords = True
                return True

            if not parsed_ids and parser.parse_optional_keyword("ids"):
                parser.parse_punctuation("=")
                values = parser.parse_comma_separated_list(
                    parser.Delimiter.SQUARE,
                    lambda: parser.parse_integer(allow_boolean=False),
                )
                self.ids_attr.set(state, ArrayAttr([IntAttr(v) for v in values]))
                parsed_ids = True
                return True

            return False

        if not _parse_one():
            return False

        if parser.parse_optional_punctuation(",") and not _parse_one():
            parser.raise_error("Expected 'coords' or 'ids' keyword after ','.")

        return True

    @override
    def print(self, printer: Printer, state: PrintingState, op: IRDLOperation) -> None:
        state.print_whitespace(printer)
        coords_attr = self.coords_attr.get(op)
        ids_attr = self.ids_attr.get(op)

        if coords_attr is not None:
            assert isa(coords_attr, ArrayAttr[QubitCoordinateAttr])
            printer.print_string("coords = ")
            with printer.in_square_brackets():
                printer.print_list(
                    coords_attr,
                    lambda coord: coord.print_parameters(printer),
                )

        if ids_attr is not None:
            assert isa(ids_attr, ArrayAttr[IntAttr])
            if coords_attr is not None:  # Only print a comma if coords were printed first
                printer.print_string(", ")
            printer.print_string("ids = ")
            with printer.in_square_brackets():
                printer.print_list(ids_attr, lambda value: printer.print_int(value.data))

    @override
    def is_optional_like(self) -> bool:
        return True

    @override
    def is_anchorable(self) -> bool:
        return True

    @override
    def is_present(self, op: IRDLOperation) -> bool:
        return self.coords_attr.get(op) is not None or self.ids_attr.get(op) is not None

    @classmethod
    def use(cls, coords_arg: str, ids_arg: str) -> str:
        """Get an assembly format fragment that will use this CustomDirective."""
        return f"custom<{cls.__name__}>({coords_arg}, {ids_arg})"


@irdl_attr_definition
class PauliNoiseParametersAttr(PlainParsableParameterizedAttribute):
    """An attribute for defining the correlated Pauli noise across several qubits.

    N-qubit correlated noise is represented as a rank-N tensor with length 4 dimensions.
    Each rank of the tensor has 4 possible indices that refer to that rank's Pauli: I, X, Y, Z.
    The sum of all probabilities in the tensor must be 1.0, this is verified to be within a
    tolerance.
    eg.
        For 2 qubit noise the tensor has shape 4x4.
        The value at (0,0) defines the II probability while (2,3) defines the YZ probability.

    This is printed and parsed as a sparse mapping from pauli-strings (including I) to probabilities
    where the identity noise probability is omitted and recalculated unless there is no other
    non-zero noise probabilities.
    eg.::

        qref.noise_parameters<X=0.25, Y=0.25, Z=0.25> // Uniform single-qubit noise
        qref.noise_parameters<IX=0.1, XX=0.4, ZI=0.2> // II is assumed to be 0.3
        qref.noise_parameters<YYYYY=0.1> // Any number of qubits can be correlated, eg 5.
        qref.noise_parameters<II=1.0>
        // If all values that aren't identity are 0.0 then the identity probability is printed.
    """

    name = "qcore.pauli_noise_parameters"

    _INDEX_ORDER: ClassVar[tuple[None, PauliAttr, PauliAttr, PauliAttr]] = (
        None,
        PauliAttr.X(),
        PauliAttr.Y(),
        PauliAttr.Z(),
    )
    """The order that defines how each dimension of the tensor is used. This is considered Final."""

    _INDEX_ORDER_STRING: ClassVar[str] = "".join(
        [pauli.data.name if pauli else "I" for pauli in _INDEX_ORDER]
    )
    """The characters for each Pauli (including 'I') in their index order. This is considered
    Final."""

    tensor: DenseIntOrFPElementsAttr[Float64Type] = param_def(
        ParamAttrConstraint[DenseIntOrFPElementsAttr[Float64Type]].get(
            DenseIntOrFPElementsAttr,
            TensorType.constr(
                Float64Type,
                MessageConstraint(
                    ArrayOfConstraint(RangeOf(IntAttr(4)).of_length(AtLeast(1))),
                    "The pauli noise tensor shape must be length 4 in each rank/dimension "
                    "and have 1 rank per qubit.",
                ),
            ),
            None,
        )
    )

    @override
    def verify(self) -> None:
        """Verifies the sum of all probabilities is close to 1.0 and none are negative."""
        if not math.isclose(total := sum(self.tensor.get_values()), 1.0):
            msg = f"The sum of noise probabilities must sum to 1.0 but got {total}."
            raise VerifyException(msg)
        if any(p < 0 for p in self.tensor.get_values()):
            index, val = next(filter(lambda p: p[1] < 0, enumerate(self.tensor.get_values())))
            msg = (
                "Noise probabilities must be non-negative but got "
                f"{self._index_to_ident(index)} = {val}."
            )
            raise VerifyException(msg)

    def qubit_count(self) -> int:
        """Returns the number of qubits this PauliNoiseParametersAttr applies to."""
        return len(self.tensor.type.shape)

    @classmethod
    def from_pauli(cls, pauli: Pauli, probability: float) -> Self:
        """Returns a NoiseParametersAttr for a single Pauli flip error with the given
        probability."""
        return cls.from_pauli_strings_dict({(PauliAttr.coerce(pauli),): probability})

    @classmethod
    def single_pauli(cls, x_p: float, y_p: float, z_p: float) -> Self:
        """Returns a NoiseParametersAttr for a single qubit pauli error with the given probabilities
        for each of the X, Y, Z error possibilities."""
        return cls.from_pauli_strings_dict(
            {
                (PauliAttr.X(),): x_p,
                (PauliAttr.Y(),): y_p,
                (PauliAttr.Z(),): z_p,
            }
        )

    @classmethod
    def two_pauli(
        cls,
        ix_p: float,
        iy_p: float,
        iz_p: float,
        xi_p: float,
        xx_p: float,
        xy_p: float,
        xz_p: float,
        yi_p: float,
        yx_p: float,
        yy_p: float,
        yz_p: float,
        zi_p: float,
        zx_p: float,
        zy_p: float,
        zz_p: float,
    ) -> Self:
        """Returns a NoiseParametersAttr for a two-qubit Pauli error with the given probabilities
        for each of the 15 non-identity Pauli pair possibilities."""
        x, y, z = PauliAttr.X(), PauliAttr.Y(), PauliAttr.Z()
        return cls.from_pauli_strings_dict(
            {
                (None, x): ix_p,
                (None, y): iy_p,
                (None, z): iz_p,
                (x, None): xi_p,
                (x, x): xx_p,
                (x, y): xy_p,
                (x, z): xz_p,
                (y, None): yi_p,
                (y, x): yx_p,
                (y, y): yy_p,
                (y, z): yz_p,
                (z, None): zi_p,
                (z, x): zx_p,
                (z, y): zy_p,
                (z, z): zz_p,
            }
        )

    @classmethod
    def depolarise(cls, qubits: int, probability: float, inclusive: bool = False) -> Self:
        """Returns a NoiseParametersAttr for a depolarisation noise with given probability across
        multiple qubits.

        Arguments:
            qubits: The number of qubits the noise is applied to.
            probability: The probability of depolarisation, the exact semantics are determined by
                the value of ``inclusive``.
            inclusive: If False, then the given probability is divided across the non-identity
                parameters, otherwise the given probability is divided across all possibilities
                such that all non-identity parameters will have value `p` and the identity parameter
                will have ``(1-probability)+p``.

        Returns:
            A PauliNoiseParametersAttr representing a depolarisation noise.
        """

        coords = list(itertools.product(range(4), repeat=qubits))[1:]
        total = len(coords) + (1 if inclusive else 0)
        return cls.from_tensor_coord_dict(dict.fromkeys(coords, probability / total))

    @classmethod
    def uniform(cls, qubits: int) -> Self:
        """Returns a NoiseParameterAttr uniform noise for all possibilities for the given number of
        qubits."""
        coords = list(itertools.product(range(4), repeat=qubits))
        total = len(coords)
        return cls.from_tensor_coord_dict(dict.fromkeys(coords, 1.0 / total))

    @classmethod
    def from_pauli_strings_dict(cls, mapping: Mapping[Sequence[PauliAttr | None], float]) -> Self:
        """Returns a NoiseParametersAttr derived from the given mapping of Pauli strings to
        probabilities.

        Pauli strings are represented by a sequence of `PauliAttr` or `None` where `None` means 'I'
        in the Pauli string.
        All the Pauli string sequences must be the same length.
        Identity will be inferred if not given explicitly.
        """
        return cls.from_tensor_coord_dict(
            {
                tuple(cls._pauli_to_index(pauli) for pauli in pauli_string): p
                for pauli_string, p in mapping.items()
            }
        )

    @classmethod
    def from_str_dict(cls, mapping: Mapping[str, float]) -> Self:
        """Returns a NoiseParametersAttr derived from the given mapping of Pauli strings to
        probabilities.

        Pauli strings are represented by a string of 'I', 'X', 'Y', 'Z' characters.
        All the Pauli string sequences must be the same length.
        Identity will be inferred if not given explicitly.
        """
        return cls.from_tensor_coord_dict(
            {cls._ident_to_tensor_coord(ident): p for ident, p in mapping.items()}
        )

    @classmethod
    def from_tensor_coord_dict(cls, mapping: Mapping[tuple[int, ...], float]) -> Self:
        """Returns a NoiseParametersAttr derived from the given mapping of tensor coordinates to
        probabilities.

        The tensor coordinates refer directly to the positions within the tensor representation of
        the noise, as so each one defines a possible Pauli string error possibility.
        All the coordinate tuples must be the same length.
        Identity will be inferred if not given explicitly.

        The coordinate for any given Pauli string can be derived by mapping each Pauli matrix in
        the Pauli string to the corresponding index: `I -> 0, X -> 1, Y -> 2, Z -> 3`. Eg. `XXYI`
        has the coordinate `(1,1,2,0)`.
        """
        return cls(cls._tensor_from_tensor_coord_dict(mapping))

    @classmethod
    def _tensor_from_ident_dict(
        cls, mapping: Mapping[str, float]
    ) -> DenseIntOrFPElementsAttr[Float64Type]:
        return cls._tensor_from_tensor_coord_dict(
            {cls._ident_to_tensor_coord(ident): p for ident, p in mapping.items()}
        )

    @classmethod
    def _tensor_from_tensor_coord_dict(
        cls, mapping: Mapping[tuple[int, ...], float]
    ) -> DenseIntOrFPElementsAttr[Float64Type]:
        qubits_set = {len(key) for key in mapping}
        if len(qubits_set) != 1:
            msg = "All tensor coordinates must have the same number of indices/Paulis."
            raise ValueError(msg)
        qubits = qubits_set.pop()
        i_parameter = tuple(0 for _ in range(qubits))
        if i_parameter not in mapping:
            mapping = dict(mapping) | {i_parameter: 1.0 - sum(mapping.values())}
        return DenseIntOrFPElementsAttr.from_list(
            TensorType(Float64Type(), [4] * qubits),
            [mapping.get(coord, 0.0) for coord in itertools.product(range(4), repeat=qubits)],
        )

    @staticmethod
    def _pauli_to_index(pauli: PauliAttr | None) -> int:
        if pauli == PauliAttr.X():
            return 1
        if pauli == PauliAttr.Y():
            return 2
        if pauli == PauliAttr.Z():
            return 3
        assert pauli is None
        return 0

    @classmethod
    def _ident_to_tensor_coord(cls, ident: str) -> tuple[int, ...]:
        try:
            return tuple(cls._INDEX_ORDER_STRING.index(char) for char in ident)
        except ValueError:
            msg = (
                f"'{next(filter(lambda c: c not in cls._INDEX_ORDER_STRING, ident))}' "
                "is not a valid part of a probability identifier."
            )
            raise ValueError(msg) from None

    @classmethod
    def _tensor_coord_to_ident(cls, coord: tuple[int, ...]) -> str:
        return "".join([cls._INDEX_ORDER_STRING[c] for c in coord])

    def _index_to_coord(self, index: int) -> tuple[int, ...]:
        dim = self.qubit_count()
        assert 0 <= index < 4**dim
        coord = [0] * dim
        while index:
            dim -= 1
            index, coord[dim] = divmod(index, 4)
        return tuple(coord)

    def _index_to_ident(self, index) -> str:
        return self._tensor_coord_to_ident(self._index_to_coord(index))

    @override
    @classmethod
    def parse_inner_parameters(cls, parser: AttrParser) -> Sequence[Attribute]:
        """Parses the inner data plainly into the Attributes that parameterise this attribute
        without surrounding bracketing.
        parses things in the form::

            ident `=` number (`,` ident `=` number)*

        where each `ident` is then parsed into a Pauli string as::

            (`I`|`X`|`Y`|`Z`)+

        and each `number` is the corresponding probability of that Pauli string being the noise
        applied.
        """
        start_point = parser.pos
        values_dict: dict[str, float] = {}
        has_next = True
        while has_next:
            ident = parser.parse_identifier(f" in the form [{cls._INDEX_ORDER_STRING}]+")
            parser.parse_punctuation("=")
            value = parse_float64(parser)
            values_dict[ident] = value
            has_next = bool(parser.parse_optional_punctuation(","))

        try:
            tensor_attr = cls._tensor_from_ident_dict(values_dict)
        except ValueError as error:
            msg = (
                "Expected noise parameters as a list of "
                f"({'|'.join('`' + c + '`' for c in cls._INDEX_ORDER_STRING)})+ `=` probability\n"
                f"Underlying error: {error!s}"
            )
            parser.raise_error(msg, start_point, parser.pos)
        return [tensor_attr]

    @override
    def print_inner(self, printer) -> None:
        """Prints the inner data plainly as a list of non-zero probabilities without surrounding
        bracketing.
        Prints things in the form::

            ident `=` number (`,` ident `=` number)*

        where each `ident` is a Pauli string for the corresponding probability number.
        The identity Pauli string `I`+ is only printed if it is the only non-zero probability.
        """
        qubits = len(self.tensor.type.shape)
        assert all(length.data == 4 for length in self.tensor.type.shape)

        first = True
        for coord, p in zip(
            itertools.product(range(4), repeat=qubits),
            self.tensor.get_values(),
            strict=True,
        ):
            if p == 0.0:
                continue  # Print sparsely
            if all(c == 0 for c in coord):
                continue  # Dont't print the II... parameter
            if not first:
                printer.print_string(", ")
            first = False

            printer.print_string(self._tensor_coord_to_ident(coord))
            printer.print_string(" = ")
            printer.print_string(float64_to_string(p))
        if first:
            # Nothing was printed at all, so we should fall back to printing the II... parameter
            # Which if all other values were 0.0, is guaranteed to be 1.0
            printer.print_string("I" * qubits)
            printer.print_string(" = ")
            printer.print_string(float64_to_string(1.0))

    def get_pauli_map(self) -> dict[tuple[PauliAttr | None, ...], float]:
        """Returns a mapping from Pauli strings to probabilities for this noise, where Pauli strings
        are represented as tuples of `PauliAttr` or `None` where `None` means 'I' in the Pauli
        string."""
        qubits = self.qubit_count()
        return {
            tuple(self._INDEX_ORDER[pauli] for pauli in coord): p
            for coord, p in zip(
                itertools.product(range(4), repeat=qubits),
                self.tensor.get_values(),
                strict=True,
            )
            if p != 0.0
        }

    @classmethod
    def constr(
        cls, qubits_constraint: int | IntConstraint
    ) -> AttrConstraint[PauliNoiseParametersAttr]:
        """Returns a constraint then verifies the attribute is a PauliNoiseParametersAttr that
        parametrises ``qubit_constraint`` qubits."""
        return ParamAttrConstraint(
            PauliNoiseParametersAttr,
            (
                ParamAttrConstraint.get(
                    DenseIntOrFPElementsAttr,
                    TensorType.constr(
                        shape=ArrayOfConstraint(RangeOf(AnyAttr()).of_length(qubits_constraint)),
                    ),
                    None,
                ),
            ),
        )


