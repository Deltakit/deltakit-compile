class IsCircuit(OpTrait):
    """A trait that indicates that the operation is a quantum circuit, so may be used as a container
    for physical circuit ops. This restricts the op to not contain any control flow."""

    @override
    def verify(self, op: Operation) -> None:
        """Verify that the op doesn't contain any scf ops or ops that also have the IsCircuit
        trait."""
        from deltakit_compile.dialects.scf import Scf  # noqa: PLC0415

        for child_op in op.walk():
            if child_op.dialect_name() == Scf.name:
                msg = (
                    "A circuit op (an op with the IsCircuit trait) may not contain "
                    f"control flow op '{child_op.name}'"
                )
                raise VerifyException(msg)
            if child_op is not op and child_op.has_trait(IsCircuit):
                msg = (
                    "A circuit op (an op with the IsCircuit trait) may not contain "
                    f"another circuit op: '{child_op.name}'"
                )
                raise VerifyException(msg)


class HasCircuitAncestor(OpTrait):
    """A trait that indicates that the operation must be contained within a circuit op."""

    @override
    def verify(self, op: Operation) -> None:
        """Verify that the op is inside a circuit op."""
        if op.parent_op() is not None and not self.has_circuit_ancestor(op):
            msg = "Op must be inside a circuit (an op with the IsCircuit trait)."
            raise VerifyException(msg)

    @staticmethod
    def _walk_ancestors(op: Operation) -> Iterator[Operation]:
        """Iterates over the ancestors of an operation, including itself."""
        curr: Operation | None = op
        while curr is not None:
            yield curr
            curr = curr.parent_op()

    @staticmethod
    def get_circuit_ancestor(op: Operation) -> Operation | None:
        """Get the most recent circuit ancestor or None if one doesn't exist."""
        for a in HasCircuitAncestor._walk_ancestors(op):
            if a.has_trait(IsCircuit):
                return a
        return None

    @staticmethod
    def has_circuit_ancestor(op: Operation) -> bool:
        return HasCircuitAncestor.get_circuit_ancestor(op) is not None


class IsProgram(OpTrait):
    """A trait that indicates that the operation is the root of a quantum program, so may be used
    as a top-level container that can manage the allocation of physical resources such as qubits.

    ``ModuleOp`` is always a program too, even though it does not carry this trait: we special-case
    it in ``is_program`` below instead of attaching the trait to it directly (e.g. via
    ``ModuleOp.traits.add_trait(IsProgram())``), to avoid mutating a class owned by
    ``xdsl.dialects.builtin`` as an import-time side effect of importing this module.
    """

    @override
    def verify(self, op: Operation) -> None:
        """Verify that op is not nested inside another program op: it must be the root of its
        program. A ``ModuleOp`` ancestor is not a program op for this purpose."""
        parent = op.parent_op()
        while parent is not None:
            if parent.has_trait(IsProgram):
                msg = (
                    "A program op (an op with the IsProgram trait) must be the root of its "
                    "program: it cannot be nested inside another program op."
                )
                raise VerifyException(msg)
            parent = parent.parent_op()

    @staticmethod
    def is_program(op: Operation) -> bool:
        """Return whether op is a program: either an op with the IsProgram trait, or a
        ``builtin.module``, which is implicitly a program. See the class docstring for why
        ``ModuleOp`` is special-cased here rather than carrying the trait itself."""
        return isinstance(op, ModuleOp) or op.has_trait(IsProgram)


class HasProgramParent(OpTrait):
    """A trait that enforces that the operation is the direct child of a program op (as defined by
    the IsProgram trait)."""

    @override
    def verify(self, op: Operation) -> None:
        """Verify that the op's direct parent is a program op."""
        if op.parent_op() is not None and not self.has_program_parent(op):
            msg = "Op must be a direct child of a program (an op with the IsProgram trait)."
            raise VerifyException(msg)

    @staticmethod
    def get_program_parent(op: Operation) -> Operation | None:
        """Get the op's parent if it is a program, or None otherwise."""
        parent = op.parent_op()
        if parent is not None and IsProgram.is_program(parent):
            return parent
        return None

    @staticmethod
    def has_program_parent(op: Operation) -> bool:
        return HasProgramParent.get_program_parent(op) is not None


